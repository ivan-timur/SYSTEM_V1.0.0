'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8');
const source = read('css/refinements/rewards-miniature.css');
const bundle = read('css/system.css');
const builder = read('scripts/build-css.js');
const androidCss = read('android/app/src/main/assets/www/css/system.css');
assert.ok(builder.includes('css/refinements/rewards-miniature.css'), 'reward refinement must be included in CSS build');
assert.ok(bundle.includes('Source: css/refinements/rewards-miniature.css'), 'runtime bundle must contain the refinement');
assert.ok(androidCss.includes('Rewards Miniature Couture'), 'Android web assets must include the same reward styles');
assert.match(source, /\.reward-card[\s\S]*?min-height:\s*142px;/, 'reward tiles must be compact');
assert.match(source, /\.ra-route-card[\s\S]*?min-height:\s*150px;/, 'milestone challenges must be compact');
assert.match(source, /max-width:\s*420px[\s\S]*?grid-template-columns:\s*repeat\(2, minmax\(0, 1fr\)\)/, 'mobile reward tiles should stay compact in a two-column layout');
assert.match(source, /prefers-reduced-motion:\s*reduce/, 'motion preferences must be respected');
assert.doesNotMatch(source, /!important\s*;/, 'reward refinement must avoid important overrides');
console.log('SYSTEM Rewards Miniature Couture checks passed: compact cards, mobile layout, Android bundle, and accessibility safeguards verified.');
