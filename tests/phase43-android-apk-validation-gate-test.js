'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const preflight = read('scripts/android-build-preflight.js');
const builder = read('scripts/build-android-debug.js');
const pkg = JSON.parse(read('package.json'));
const debugWorkflow = read('.github/workflows/build-android.yml');
const releaseWorkflow = read('.github/workflows/release-android.yml');
const androidReadme = read('android/README.md');
assert(preflight.includes("const strict = process.argv.includes('--strict')"), 'preflight must support strict blocking mode');
assert(preflight.includes("process.exitCode = 2"), 'strict preflight must fail when required tooling is missing');
assert(builder.includes("'--strict'"), 'APK builder must enforce strict preflight before building');
assert(builder.includes("assembleDebug"), 'debug builder must invoke the actual Gradle assembleDebug task');
assert(builder.includes("fs.statSync(apk).size === 0"), 'APK builder must reject missing or empty APK artifact');
assert(pkg.scripts['android:preflight'] && pkg.scripts['android:build:debug'], 'package scripts must expose Android preflight and debug build');
assert(/gradle-version:\s*'8\.13'/.test(debugWorkflow) && /platforms;android-36/.test(debugWorkflow), 'debug CI must pin Gradle and Android SDK platform');
assert(/apksigner" verify/.test(releaseWorkflow) && /sha256sum/.test(releaseWorkflow), 'release workflow must verify APK signature and checksum');
assert(androidReadme.includes('app/build/outputs/apk/debug/app-debug.apk'), 'Android docs must name expected debug APK output');
console.log('PASS Phase 43 Android APK validation gate: strict preflight, real build task, artifact check, CI pins and release verification');
