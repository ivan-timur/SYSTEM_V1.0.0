'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8');

const updater = read('android/app/src/main/java/com/cronus/system/GitHubReleaseUpdater.java');
const activity = read('android/app/src/main/java/com/cronus/system/MainActivity.java');
const manifest = read('android/app/src/main/AndroidManifest.xml');
const filePaths = read('android/app/src/main/res/xml/file_paths.xml');
const nativeModule = read('js/modules/android-native.js');
const html = read('index.html');
const workflow = read('.github/workflows/release-android.yml');
const versionSync = read('scripts/sync-version.js');

assert.match(updater, /api\.github\.com\/repos\/" \+ OWNER \+ "\/" \+ REPOSITORY \+ "\/releases\/latest/);
assert.match(updater, /AndroidKeyStore/);
assert.match(updater, /AES\/GCM\/NoPadding/);
assert.match(updater, /TOKEN_PATTERN/);
assert.match(updater, /MAX_TOKEN_CHARS = 512/);
assert.match(updater, /Stored token has an invalid format/);
assert.match(updater, /getCanonicalFile\(\)/, 'Pending APK paths must be canonicalized before installation.');
assert.match(updater, /The saved update file failed validation/);
assert.match(updater, /validateAssetRedirect/);
assert.match(updater, /url\.getUserInfo\(\) == null/);
assert.match(updater, /url\.getPort\(\)/);
assert.match(updater, /JSONObject\.quote\(data\.toString\(\)\)/, 'Native bridge events must be serialized as quoted JSON, not spliced directly into JavaScript.');
assert.match(updater, /JSON\.parse\(" \+ payload \+ "\)/);
assert.match(updater, /remove\(PENDING_INSTALL_KEY\)/);
assert.match(updater, /findReleaseChecksum/);
assert.match(updater, /MessageDigest\.getInstance\(\"SHA-256\"\)/);
assert.match(updater, /readExpectedSha256\(checksumFile, apkFile\.getName\(\)\)/);
assert.match(updater, /verifySha256\(apkFile, expectedSha256\)/);
assert.match(updater, /checksum-invalid/);
assert.match(updater, /expectedApkName\.equals\(checkedName\)/, 'A release checksum must bind to the expected APK filename.');
assert.match(updater, /checksum-missing/);
assert.match(updater, /BuildConfig\.DEBUG/);
assert.match(updater, /ACTION_VIEW/);
assert.match(updater, /canRequestPackageInstalls/);
assert.doesNotMatch(updater, /ghp_[A-Za-z0-9]{35,}/, 'A real PAT must never be committed in source.');
assert.match(activity, /new GitHubReleaseUpdater\(this, webView\)/);
assert.match(activity, /downloadLatestUpdate\(\)/);
assert.match(manifest, /REQUEST_INSTALL_PACKAGES/);
assert.match(manifest, /androidx\.core\.content\.FileProvider/);
assert.match(manifest, /\$\{applicationId\}\.updateprovider/);
assert.match(filePaths, /cache-path[^>]+path="updates\/"/);
assert.match(nativeModule, /system-android-update/);
assert.match(nativeModule, /getLastUpdateCheckMillis/);
assert.match(html, /id="system-github-updater"/);
assert.match(html, /id="system-update-check"/);
assert.match(html, /id="system-update-download"/);
assert.match(workflow, /tags:/);
assert.match(workflow, /ANDROID_KEYSTORE_BASE64/);
assert.match(workflow, /assembleRelease/);
assert.match(workflow, /apksigner/);
assert.match(workflow, /sha256sum/);
assert.match(workflow, /SYSTEM-\*\.apk\.sha256/);
assert.match(updater, /MAX_CHECKSUM_BYTES/);
assert.match(nativeModule, /checksum-missing/);
assert.match(workflow, /contents: write/);
assert.match(workflow, /Run static regression suite/);
assert.match(workflow, /Run project health checks/);
assert.match(workflow, /Run real-browser release checks/);
assert.match(workflow, /npm run test:e2e/);
assert.match(versionSync, /androidVersionCode/);
console.log('PASS Android GitHub release updater configuration');
