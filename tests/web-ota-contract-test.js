'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8');
const pkg = JSON.parse(read('package.json'));
const manager = read('android/app/src/main/java/com/cronus/system/WebUpdateManager.java');
const activity = read('android/app/src/main/java/com/cronus/system/MainActivity.java');
const githubUpdater = read('android/app/src/main/java/com/cronus/system/GitHubReleaseUpdater.java');
const sync = read('scripts/sync-android-assets.js');
const packager = read('scripts/package-web-ota.js');
const workflow = read('.github/workflows/publish-web-ota.yml');
const native = read('js/modules/android-native.js');
const html = read('index.html');
const guide = read('docs/WEB_OTA_GUIDE_FA.md');

assert.equal(read('WEB_VERSION').trim(), '1.0.0', 'Initial web version must be independently versioned.');
assert.equal(read('WEB_MIN_NATIVE_VERSION').trim(), '1.0.0', 'Initial OTA package must declare a native compatibility floor.');
assert.match(sync, /'WEB_VERSION'/, 'The bundled native app must know its starting Web OTA version.');
assert.match(packager, /deflateRawSync/, 'OTA ZIP must be packaged without an external ZIP dependency.');
assert.match(packager, /sha256/, 'OTA manifest must include a SHA-256 digest.');
assert.match(packager, /minNativeVersion/, 'OTA manifest must declare minimum supported native version.');
assert.match(manager, /verifySha256/, 'Native manager must verify the bundle before extraction.');
assert.match(manager, /validateZipEntryName/, 'Native manager must reject ZIP path traversal.');
assert.match(manager, /MAX_EXPANDED_BYTES/, 'Native manager must enforce an expanded bundle size limit.');
assert.match(manager, /PENDING_CONFIRMATION/, 'OTA activation must support crash recovery.');
assert.match(manager, /prepareForLaunch/, 'A failed first launch must roll back to the prior version.');
assert.match(manager, /getGitHubTokenForWebUpdate/, 'OTA must use the encrypted native token, not web storage.');
assert.match(manager, /system-ota/, 'OTA must use a branch separate from GitHub APK Releases.');
assert.match(activity, /new WebUpdateManager\(this, webView, githubReleaseUpdater\)/);
assert.match(activity, /new SystemAssetPathHandler\(\)/, 'Verified OTA files must be served from local storage.');
assert.match(activity, /Do not mix an OTA version with files from the older bundled version/);
assert.match(activity, /applyWebUpdate\(\)/);
assert.match(githubUpdater, /getGitHubTokenForWebUpdate\(\)/);
assert.match(html, /id="system-web-updater"/);
assert.match(html, /id="system-web-update-check"/);
assert.match(html, /id="system-web-update-apply"/);
assert.match(native, /system-android-web-update/);
assert.match(native, /checkForWebUpdates/);
assert.match(native, /window\.location\.reload\(\)/);
assert.match(workflow, /publish SYSTEM web-only OTA bundle/i);
assert.match(workflow, /branches:/);
assert.match(workflow, /system-ota/);
assert.match(workflow, /WEB_VERSION/);
assert.match(workflow, /current\.minNativeVersion !== previous\.minNativeVersion/);
assert.match(workflow, /npm test/);
assert.match(workflow, /push --force origin HEAD:system-ota/);
assert.doesNotMatch(workflow, /assembleRelease|assembleDebug/, 'The web OTA workflow must not build an APK.');
assert.equal(pkg.scripts['package:web-ota'], 'npm run prepare:android && node scripts/package-web-ota.js');
assert.match(pkg.scripts['test:static'], /tests\/web-ota-contract-test\.js/);
assert.match(guide, /APK/i);
assert.match(guide, /WEB_VERSION/);
console.log('PASS SYSTEM Web OTA contract: independent channel, versioning, integrity checks, local-only loading and rollback.');
