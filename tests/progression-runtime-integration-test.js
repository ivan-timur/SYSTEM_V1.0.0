"use strict";
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ROOT = path.resolve(__dirname, '..');
const runtime = fs.readFileSync(path.join(ROOT, 'js/generated/progression-math.js'), 'utf8');
const adapter = fs.readFileSync(path.join(ROOT, 'js/core/progression-math.js'), 'utf8');
const legacy = fs.readFileSync(path.join(ROOT, 'js/legacy/app-controller.js'), 'utf8');
const playerStart = legacy.indexOf('function addPlayerXP(amount) {');
const playerEnd = legacy.indexOf('/* =========================================================\n   15. ADD STAT XP', playerStart);
const statStart = legacy.indexOf('function addStatXP(statName, amount) {');
const statEnd = legacy.indexOf('/* Central XP pipeline', statStart);
assert.ok(playerStart >= 0 && playerEnd > playerStart, 'Player XP entry point must remain present');
assert.ok(statStart >= 0 && statEnd > statStart, 'Stat XP entry point must remain present');
const mathWindow = {};
const mathSandbox = { window: mathWindow, globalThis: {}, Number, Math, Object, String, Error };
vm.createContext(mathSandbox);
vm.runInContext(runtime, mathSandbox, { filename: 'js/generated/progression-math.js' });
vm.runInContext(adapter, mathSandbox, { filename: 'js/core/progression-math.js' });
const math = mathWindow.SYSTEMProgressionMath;
assert.ok(Object.isFrozen(math), 'Runtime API must be immutable');
const oldPlayer = { level: 50, xp: 15790, xpRequired: math.getPlayerXPRequired(50) };
const player = math.advanceXPTrack(oldPlayer, 25, math.getPlayerXPRequired, 1000);
assert.equal(player.level, 51, 'The active Player XP curve must level up at its historical threshold');
assert.equal(player.xp, 15, 'Overflow XP must carry into the next level');
assert.equal(player.xpRequired, math.getPlayerXPRequired(51));
assert.equal(oldPlayer.level, 50, 'Transition must not mutate the persisted state object');
const stat = math.advanceXPTrack({ level: 3, xp: 0, xpRequired: math.getStatXPRequired(3) }, 300, math.getStatXPRequired, 100);
assert.ok(stat.level > 3, 'Stat track must process multiple level-ups');
assert.ok(stat.xp >= 0 && stat.xp < stat.xpRequired, 'Stat XP must end in the current level bucket unless capped');
const playerFunction = legacy.slice(playerStart, playerEnd);
const statFunction = legacy.slice(statStart, statEnd);
assert.match(playerFunction, /math\.advanceXPTrack/);
assert.match(statFunction, /math\.advanceXPTrack/);
assert.doesNotMatch(playerFunction, /while \(/, 'Legacy Player XP function must not retain a second level-up algorithm');
assert.doesNotMatch(statFunction, /while \(/, 'Legacy Stat XP function must not retain a second level-up algorithm');
console.log('TypeScript runtime progression integration passed: Player XP, Stat XP, overflow, immutability, and legacy bridge.');
