'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const pkg = JSON.parse(read('package.json'));
const script = read('scripts/build-android-debug.js');
const guide = read('android/README.md');
assert.equal(pkg.scripts['android:build:debug'], 'node scripts/build-android-debug.js');
assert.match(pkg.scripts['test:static'], /android-build-command-contract-test\.js/);
assert.match(script, /android-build-preflight\.js/);
assert.match(script, /--strict/);
assert.match(script, /prepare:android/);
assert.match(script, /assembleDebug/);
assert.match(script, /app-debug\.apk/);
assert.match(script, /BUILD SUCCESS/);
assert.match(guide, /npm run android:build:debug/);
console.log('PASS Android debug build command contract checks');
